// ClipVault: an encrypted, text-only clipboard history.
//
//   clipvault watch   run forever, recording new clipboard text (used by the LaunchAgent)
//   clipvault list    print one sanitized preview line per history item, newest first
//   clipvault copy    read a line from `list` on stdin and put that item back on the clipboard
//   clipvault clear   delete the history and its encryption key
//
// History is AES-256-GCM encrypted with a random key kept in the login Keychain. The key is
// replaced daily and deleted by `clear`, so old ciphertext left on disk can't be decrypted with
// the live Keychain. (A snapshot of the login Keychain from the same time could still hold it.)

import AppKit
import CryptoKit
import Foundation
import LocalAuthentication
import Security

let maxItems = 50
let maxAge: TimeInterval = 24 * 60 * 60
let keyLifetime: TimeInterval = 24 * 60 * 60
let maxBytes = 100_000
let previewLength = 80
let pollInterval: TimeInterval = 0.5
let maintenanceInterval: TimeInterval = 60

// Markers that password managers and other apps put on secrets they copy.
// See http://nspasteboard.org
let skippedTypes: Set<String> = [
    "org.nspasteboard.ConcealedType",
    "org.nspasteboard.TransientType",
    "org.nspasteboard.AutoGeneratedType",
    "com.agilebits.onepassword",
    "de.petermaurer.TransientPasteboardType",
]

// Overridable only so test.sh can use a throwaway folder and Keychain item.
let environment = ProcessInfo.processInfo.environment
let supportDir = environment["CLIPVAULT_DIR"].map { URL(fileURLWithPath: $0, isDirectory: true) }
    ?? FileManager.default.homeDirectoryForCurrentUser
        .appendingPathComponent("Library/Application Support/ClipVault", isDirectory: true)
let keychainService = environment["CLIPVAULT_KEYCHAIN_SERVICE"] ?? "ClipVault"
let historyURL = supportDir.appendingPathComponent("history.enc")
let lockURL = supportDir.appendingPathComponent("history.lock")

struct Entry: Codable, Equatable {
    var id: String
    var text: String
    var date: Date

    init(id: String, text: String, date: Date) {
        self.id = id
        self.text = text
        self.date = date
    }

    // Histories written before ids existed decode with an empty id; loadHistory assigns one.
    init(from decoder: Decoder) throws {
        let container = try decoder.container(keyedBy: CodingKeys.self)
        id = try container.decodeIfPresent(String.self, forKey: .id) ?? ""
        text = try container.decode(String.self, forKey: .text)
        date = try container.decode(Date.self, forKey: .date)
    }
}

struct ClipVaultError: Error, CustomStringConvertible {
    let description: String
}

func describe(_ error: Error) -> String {
    (error as? ClipVaultError)?.description ?? error.localizedDescription
}

func log(_ message: String) {
    let stamp = ISO8601DateFormatter().string(from: Date())
    FileHandle.standardError.write(Data("\(stamp) \(message)\n".utf8))
}

// MARK: - Keychain

// During a rotation the new key is stored under `nextKeyAccount` until the file is re-encrypted,
// so a crash at any point leaves a key that opens the file.
let currentKeyAccount = "history-key"
let nextKeyAccount = "history-key-next"

func keychainItem(_ account: String, allowInteraction: Bool) -> [String: Any] {
    var item: [String: Any] = [
        kSecClass as String: kSecClassGenericPassword,
        kSecAttrService as String: keychainService,
        kSecAttrAccount as String: account,
    ]
    // This covers access-control prompts (Touch ID, passcode). It does NOT stop the login
    // Keychain's "allow access" prompt; see disableKeychainPrompts for that.
    if !allowInteraction {
        let context = LAContext()
        context.interactionNotAllowed = true
        item[kSecUseAuthenticationContext as String] = context
    }
    return item
}

/// Makes every Keychain call in this process fail with errSecInteractionNotAllowed instead of showing
/// a prompt. Without this, a prompt (e.g. after a rebuild changes the binary's signature) blocks the
/// watcher indefinitely while it holds the history lock, which also freezes the picker.
///
/// SecKeychainSetUserInteractionAllowed is deprecated, but it is the only switch that covers the login
/// Keychain's access prompt: LAContext.interactionNotAllowed doesn't, and the data-protection Keychain
/// (where LAContext would be enough) requires a signed binary with a Keychain entitlement. It is looked
/// up at runtime so the build stays free of deprecation warnings under -warnings-as-errors.
func disableKeychainPrompts() -> Bool {
    typealias SetUserInteractionAllowed = @convention(c) (UInt8) -> OSStatus
    // RTLD_DEFAULT is ((void *)-2) on Darwin; Swift doesn't import the macro.
    guard let symbol = dlsym(UnsafeMutableRawPointer(bitPattern: -2), "SecKeychainSetUserInteractionAllowed")
    else { return false }
    return unsafeBitCast(symbol, to: SetUserInteractionAllowed.self)(0) == errSecSuccess
}

func keychainError(_ action: String, _ status: OSStatus) -> ClipVaultError {
    let message = SecCopyErrorMessageString(status, nil) as String? ?? "OSStatus \(status)"
    let hint = status == errSecAuthFailed || status == errSecInteractionNotAllowed
        ? " Run `clipvault list` in Terminal and choose Always Allow." : ""
    return ClipVaultError(description: "Keychain \(action) failed: \(message)\(hint)")
}

/// The stored key and when it was last written, or nil if there is no key yet.
func readKey(_ account: String, allowInteraction: Bool) throws -> (key: SymmetricKey, date: Date)? {
    var query = keychainItem(account, allowInteraction: allowInteraction)
    query[kSecReturnData as String] = true
    query[kSecReturnAttributes as String] = true
    query[kSecMatchLimit as String] = kSecMatchLimitOne
    var result: CFTypeRef?
    let status = SecItemCopyMatching(query as CFDictionary, &result)
    if status == errSecItemNotFound { return nil }
    guard status == errSecSuccess else { throw keychainError("read", status) }
    guard let item = result as? [String: Any], let data = item[kSecValueData as String] as? Data, data.count == 32
    else { throw ClipVaultError(description: "Keychain item ClipVault/\(account) is malformed") }
    let date = item[kSecAttrModificationDate as String] as? Date ?? .distantPast
    return (SymmetricKey(data: data), date)
}

func storeKey(_ key: SymmetricKey, account: String, replacing: Bool, allowInteraction: Bool) throws {
    let data = key.withUnsafeBytes { Data($0) }
    let status: OSStatus
    if replacing {
        status = SecItemUpdate(
            keychainItem(account, allowInteraction: allowInteraction) as CFDictionary,
            [kSecValueData as String: data] as CFDictionary)
    } else {
        var add = keychainItem(account, allowInteraction: allowInteraction)
        add[kSecAttrLabel as String] = "ClipVault history key"
        add[kSecValueData as String] = data
        status = SecItemAdd(add as CFDictionary, nil)
    }
    guard status == errSecSuccess else { throw keychainError("write", status) }
}

func deleteKey(_ account: String, allowInteraction: Bool) throws {
    let status = SecItemDelete(keychainItem(account, allowInteraction: allowInteraction) as CFDictionary)
    guard status == errSecSuccess || status == errSecItemNotFound else { throw keychainError("delete", status) }
}

// MARK: - Storage

func prepareDirectory() throws {
    try FileManager.default.createDirectory(at: supportDir, withIntermediateDirectories: true)
    try FileManager.default.setAttributes([.posixPermissions: 0o700], ofItemAtPath: supportDir.path)
    // Keep ciphertext out of Time Machine, which also backs up the Keychain that holds old keys.
    var dir = supportDir
    var values = URLResourceValues()
    values.isExcludedFromBackup = true
    try dir.setResourceValues(values)
}

/// Runs `body` holding an exclusive lock, so the watcher, the picker and `clear` never interleave.
func locked<T>(_ body: () throws -> T) throws -> T {
    try prepareDirectory()
    let fd = open(lockURL.path, O_CREAT | O_RDWR, 0o600)
    guard fd >= 0 else { throw ClipVaultError(description: "Could not open lock: \(String(cString: strerror(errno)))") }
    defer { close(fd) }
    guard flock(fd, LOCK_EX) == 0 else {
        throw ClipVaultError(description: "Could not lock history: \(String(cString: strerror(errno)))")
    }
    return try body()
}

func pruned(_ entries: [Entry]) -> [Entry] {
    let cutoff = Date().addingTimeInterval(-maxAge)
    return Array(entries.filter { $0.date > cutoff }.prefix(maxItems))
}

func decrypt(_ data: Data, with key: SymmetricKey) -> [Entry]? {
    guard let box = try? AES.GCM.SealedBox(combined: data),
          let plain = try? AES.GCM.open(box, using: key)
    else { return nil }
    return try? JSONDecoder().decode([Entry].self, from: plain)
}

/// The history as stored on disk (not yet pruned) and the key it is encrypted with.
struct History {
    var entries: [Entry]
    var key: (key: SymmetricKey, date: Date)?
}

/// Loads the history, first finishing any key rotation that was interrupted. Call with the lock held.
/// Only a missing file reads as empty: anything that exists but can't be read or decrypted throws,
/// so nothing that might be recoverable is ever overwritten.
func loadHistory(allowKeychainInteraction: Bool) throws -> History {
    var current = try readKey(currentKeyAccount, allowInteraction: allowKeychainInteraction)
    let next = try readKey(nextKeyAccount, allowInteraction: allowKeychainInteraction)
    let data: Data?
    do {
        data = try Data(contentsOf: historyURL)
    } catch CocoaError.fileReadNoSuchFile {
        data = nil
    }

    if let next {
        // The rotation stopped after storing the next key. If the file was already re-encrypted
        // with it, finish by promoting it; otherwise the old key is still the right one.
        if let data, decrypt(data, with: next.key) != nil {
            try storeKey(
                next.key, account: currentKeyAccount, replacing: current != nil,
                allowInteraction: allowKeychainInteraction)
            current = (next.key, Date())
        }
        try deleteKey(nextKeyAccount, allowInteraction: allowKeychainInteraction)
    }

    guard let data else { return History(entries: [], key: current) }
    guard let current, var entries = decrypt(data, with: current.key) else {
        throw ClipVaultError(description:
            "History can't be decrypted, so it has been left untouched. Run `clipvault clear` to start over.")
    }
    if entries.contains(where: { $0.id.isEmpty }) {
        for index in entries.indices where entries[index].id.isEmpty {
            entries[index].id = newID(avoiding: entries)
        }
        // Save the new ids now, so `list` and `copy` agree on them.
        try writeHistory(entries, with: current.key)
    }
    return History(entries: entries, key: current)
}

func writeHistory(_ entries: [Entry], with key: SymmetricKey) throws {
    let sealed = try AES.GCM.seal(JSONEncoder().encode(entries), using: key)
    try sealed.combined!.write(to: historyURL, options: .atomic)
    try FileManager.default.setAttributes([.posixPermissions: 0o600], ofItemAtPath: historyURL.path)
}

func removeHistory() throws {
    do {
        try FileManager.default.removeItem(at: historyURL)
    } catch CocoaError.fileNoSuchFile {
    }
}

func snapshot() throws -> [Entry] {
    try locked { pruned(try loadHistory(allowKeychainInteraction: true).entries) }
}

/// Loads, changes, prunes and saves the history under the lock, replacing the key once it is
/// older than `keyLifetime`.
func update(allowKeychainInteraction: Bool, _ change: (inout [Entry]) -> Void) throws {
    try locked {
        let history = try loadHistory(allowKeychainInteraction: allowKeychainInteraction)
        var entries = history.entries
        change(&entries)
        entries = pruned(entries)
        let expired = history.key.map { Date().timeIntervalSince($0.date) > keyLifetime } ?? false

        if entries.isEmpty {
            try removeHistory()
            if expired { try deleteKey(currentKeyAccount, allowInteraction: allowKeychainInteraction) }
            return
        }
        if let current = history.key, !expired {
            if entries != history.entries { try writeHistory(entries, with: current.key) }
            return
        }
        let key = SymmetricKey(size: .bits256)
        guard history.key != nil else {
            // First key: a crash before the write just leaves a key with no history.
            try storeKey(
                key, account: currentKeyAccount, replacing: false,
                allowInteraction: allowKeychainInteraction)
            try writeHistory(entries, with: key)
            return
        }
        // Rotation. If this stops partway, loadHistory works out which key opens the file.
        try storeKey(
            key, account: nextKeyAccount, replacing: false,
            allowInteraction: allowKeychainInteraction)
        try writeHistory(entries, with: key)
        try storeKey(
            key, account: currentKeyAccount, replacing: true,
            allowInteraction: allowKeychainInteraction)
        try deleteKey(nextKeyAccount, allowInteraction: allowKeychainInteraction)
    }
}

// MARK: - Previews

/// Drops control and formatting characters (ESC, bidi overrides, zero-width marks…) so a
/// preview can't inject terminal escape sequences or disguise itself.
func isPrintable(_ scalar: Unicode.Scalar) -> Bool {
    switch scalar.properties.generalCategory {
    case .control, .format, .surrogate, .privateUse, .unassigned, .lineSeparator, .paragraphSeparator:
        return false
    default:
        return true
    }
}

func preview(_ text: String) -> String {
    var scalars = String.UnicodeScalarView()
    scalars.append(contentsOf: text.unicodeScalars.map { isPrintable($0) ? $0 : " " })
    let flat = String(scalars).split(whereSeparator: \.isWhitespace).joined(separator: " ")
    if flat.isEmpty { return "(no printable text)" }
    return flat.count > previewLength ? String(flat.prefix(previewLength)) + "…" : flat
}

/// A `list` line. The id at the end is stable for the life of the item, so `copy` finds the
/// right one even if the history changed after the picker opened.
func line(for entry: Entry) -> String {
    "\(preview(entry.text))  [\(entry.id)]"
}

func newID(avoiding entries: [Entry]) -> String {
    while true {
        let id = String(format: "%06x", UInt32.random(in: 0..<0x100_0000))
        if !entries.contains(where: { $0.id == id }) { return id }
    }
}

// MARK: - Commands

func capture(_ pasteboard: NSPasteboard, allowKeychainInteraction: Bool) throws {
    let types = Set((pasteboard.types ?? []).map(\.rawValue))
    guard types.isDisjoint(with: skippedTypes),
          let text = pasteboard.string(forType: .string),
          !text.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty,
          text.utf8.count <= maxBytes
    else { return }

    try update(allowKeychainInteraction: allowKeychainInteraction) { entries in
        let existing = entries.firstIndex { $0.text == text }
        let id = existing.map { entries[$0].id } ?? newID(avoiding: entries)
        if let existing { entries.remove(at: existing) }
        entries.insert(Entry(id: id, text: text, date: Date()), at: 0)
    }
}

struct WatchState {
    var capturedChange: Int
    private(set) var failedChange: Int?
    private(set) var lastCaptureAttempt = Date.distantPast

    func shouldCapture(change: Int, at date: Date) -> Bool {
        guard change != capturedChange else { return false }
        return change != failedChange || date.timeIntervalSince(lastCaptureAttempt) >= maintenanceInterval
    }

    mutating func recordCapture(change: Int, at date: Date, succeeded: Bool) {
        lastCaptureAttempt = date
        if succeeded {
            capturedChange = change
            failedChange = nil
        } else {
            failedChange = change
        }
    }
}

func watch() -> Never {
    if !disableKeychainPrompts() {
        log("Could not disable Keychain prompts; an access prompt may block the watcher until answered.")
    }

    let pasteboard = NSPasteboard.general
    var state = WatchState(capturedChange: pasteboard.changeCount)
    var lastMaintenance = Date.distantPast
    var lastError: String?

    // Failures (e.g. a locked Keychain) are retried on the next change or maintenance pass
    // instead of exiting, and each distinct failure is logged once.
    func attempt(_ body: () throws -> Void) -> Bool {
        do {
            try body()
            lastError = nil
            return true
        } catch {
            let message = describe(error)
            if message != lastError { log(message) }
            lastError = message
            return false
        }
    }

    while true {
        Thread.sleep(forTimeInterval: pollInterval)
        autoreleasepool {
            let now = Date()
            let change = pasteboard.changeCount
            if state.shouldCapture(change: change, at: now) {
                let succeeded = attempt {
                    try capture(pasteboard, allowKeychainInteraction: false)
                }
                state.recordCapture(change: change, at: now, succeeded: succeeded)
            } else if now.timeIntervalSince(lastMaintenance) > maintenanceInterval {
                // Expire old items and rotate the key even when nothing new is copied.
                lastMaintenance = now
                _ = attempt { try update(allowKeychainInteraction: false) { _ in } }
            }
        }
    }
}

/// Shown instead of a blank picker item. It has no id, so choosing it copies nothing.
let emptyMarker = "(clipboard history is empty)"

func list() throws {
    let entries = try snapshot()
    print(entries.isEmpty ? emptyMarker : entries.map(line).joined(separator: "\n"))
}

func copy() throws {
    let input = String(decoding: FileHandle.standardInput.readDataToEndOfFile(), as: UTF8.self)
    if input.trimmingCharacters(in: .whitespacesAndNewlines) == emptyMarker { return }
    guard let match = input.firstMatch(of: #/\[([0-9a-f]{6})\]\s*$/#) else {
        throw ClipVaultError(description: "That line has no history id.")
    }
    let id = String(match.1)
    guard let entry = try snapshot().first(where: { $0.id == id }) else {
        throw ClipVaultError(description: "That item is no longer in the history.")
    }
    let pasteboard = NSPasteboard.general
    pasteboard.clearContents()
    guard pasteboard.setString(entry.text, forType: .string) else {
        throw ClipVaultError(description: "The clipboard rejected the selected history item.")
    }
}

/// Deletes the file and the keys without reading them, so it also works on unreadable history.
/// Either one alone makes the history unreadable, so all are attempted and every failure is reported.
func clear() throws {
    try locked {
        var failures: [String] = []
        do { try removeHistory() } catch { failures.append("Could not delete history: \(describe(error))") }
        for account in [currentKeyAccount, nextKeyAccount] {
            do { try deleteKey(account, allowInteraction: true) } catch { failures.append(describe(error)) }
        }
        if !failures.isEmpty { throw ClipVaultError(description: failures.joined(separator: "\n")) }
    }
}
